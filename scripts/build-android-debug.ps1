$ErrorActionPreference = 'Stop'

$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$sdk = if ($env:ANDROID_SDK_ROOT) { $env:ANDROID_SDK_ROOT } else { Join-Path $root '.android-sdk' }
$ndk = Join-Path $sdk 'ndk\27.2.12479018'
$androidProject = Join-Path $root 'src-tauri\gen\android'
$jniDir = Join-Path $androidProject 'app\src\main\jniLibs\arm64-v8a'
$assetsDir = Join-Path $androidProject 'app\src\main\assets'

if (-not (Test-Path (Join-Path $sdk 'platforms\android-36'))) { throw "Android SDK platform android-36 is missing at $sdk" }
if (-not (Test-Path (Join-Path $ndk 'source.properties'))) { throw "Android NDK 27.2.12479018 is missing at $ndk" }
if (-not (Test-Path (Join-Path $androidProject 'gradlew.bat'))) { throw 'Tauri Android project is not initialized. Run cargo tauri android init --ci --skip-targets-install' }

$env:ANDROID_HOME = $sdk
$env:ANDROID_SDK_ROOT = $sdk
$env:NDK_HOME = $ndk
$llvmBin = Join-Path $ndk 'toolchains\llvm\prebuilt\windows-x86_64\bin'
$clang = Join-Path $llvmBin 'aarch64-linux-android24-clang.cmd'
$clangxx = Join-Path $llvmBin 'aarch64-linux-android24-clang++.cmd'
${env:CC_aarch64-linux-android} = $clang
$env:CC_aarch64_linux_android = $clang
${env:CXX_aarch64-linux-android} = $clangxx
$env:CXX_aarch64_linux_android = $clangxx
$env:CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER = $clang
$env:PATH = "$llvmBin;$env:PATH"
if (-not $env:JAVA_HOME) {
    $java = Get-Command java.exe -ErrorAction SilentlyContinue
    if ($java) { $env:JAVA_HOME = Split-Path (Split-Path $java.Source) }
}

Push-Location $root
try {
    # .cargo/config.toml may redirect the target directory, so ask Cargo rather
    # than assuming "$root\target"; a hardcoded path silently breaks the moment
    # someone moves the build cache off the project drive.
    $metadata = cargo metadata --format-version 1 --no-deps | ConvertFrom-Json
    $targetLib = Join-Path $metadata.target_directory 'aarch64-linux-android\debug\libwens_desktop_lib.so'

    cargo build --package wens-desktop --target aarch64-linux-android --features 'tauri/custom-protocol' --lib
    if ($LASTEXITCODE -ne 0) { throw "Rust cross-compile for aarch64-linux-android failed (cargo exit $LASTEXITCODE)" }
    if (-not (Test-Path $targetLib)) { throw "Cross-compiled library is missing: $targetLib" }
    New-Item -ItemType Directory -Force -Path $jniDir | Out-Null
    Copy-Item -LiteralPath $targetLib -Destination (Join-Path $jniDir 'libwens_desktop_lib.so') -Force
    # Mirror, not merge: a plain /E copy leaves retired bundles behind and the
    # APK ends up shipping a UI it no longer builds from.
    if (Test-Path $assetsDir) { Remove-Item -Recurse -Force $assetsDir }
    New-Item -ItemType Directory -Force -Path $assetsDir | Out-Null
    robocopy (Join-Path $root 'dist-vnext') $assetsDir /MIR /NFL /NDL /NJH /NJS /NC /NS | Out-Null
    if ($LASTEXITCODE -gt 7) { throw "Unable to copy frontend assets (robocopy $LASTEXITCODE)" }

    # tauri.properties is generated by `cargo tauri android init` and drifts from
    # tauri.conf.json unless it is refreshed, so the Play Store would reject an
    # upload for a version that was already published.
    $tauriConf = Get-Content -Raw (Join-Path $root 'src-tauri\tauri.conf.json') | ConvertFrom-Json
    $parts = $tauriConf.version -split '\.'
    $versionCode = ([int]$parts[1] * 1000) + [int]$parts[2]
    @(
        '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.'
        "tauri.android.versionName=$($tauriConf.version)"
        "tauri.android.versionCode=$versionCode"
    ) | Set-Content -Encoding ascii (Join-Path $androidProject 'app\tauri.properties')
    @(
        "sdk.dir=$($sdk -replace '\\','/')"
        "ndk.dir=$($ndk -replace '\\','/')"
    ) | Set-Content -Encoding ascii (Join-Path $androidProject 'local.properties')
    Push-Location $androidProject
    try {
        # Tauri normally creates symlinks; copies above keep this working on
        # Windows without Developer Mode or installer code signing.
        .\gradlew.bat assembleArm64Debug -x rustBuildArm64Debug --no-daemon
    } finally { Pop-Location }
} finally { Pop-Location }

$apk = Join-Path $androidProject 'app\build\outputs\apk\arm64\debug\app-arm64-debug.apk'
if (-not (Test-Path $apk)) { throw "APK was not produced: $apk" }
Write-Output "Android debug APK: $apk"
$sha = (certutil.exe -hashfile $apk SHA256 | Select-Object -Skip 1 -First 1).Trim()
Write-Output "SHA-256: $sha"
